import struct
import numpy as np
from pathlib import Path
import matplotlib.pyplot as plt
from collections import defaultdict

marco_dir = Path("/data/jsu068/marco")
marco_embed_dir = marco_dir / "embedding"
marco_query_dir = marco_dir / "query"

with open(marco_embed_dir / "marco.768D.10M.euclidean.fbin", "rb") as f:
    N = struct.unpack('I', f.read(4))[0]
    # dim = struct.unpack('I', f.read(4))[0]

with open(marco_embed_dir / "meta.bin", "rb") as f:
    n = struct.unpack('I', f.read(4))[0]
    # dim = struct.unpack('I', f.read(4))[0]

meta = np.memmap(marco_embed_dir / "meta.bin", dtype=np.uint32, mode='r', offset=8)

with open(marco_embed_dir / "metaidx.bin", "rb") as f:
    n = struct.unpack('I', f.read(4))[0]
    dim = struct.unpack('I', f.read(4))[0]

metaidx = np.memmap(marco_embed_dir / "metaidx.bin", dtype=np.uint8, mode='r', offset=8, shape=(n, 8))

cnt = 0
marco_embed = defaultdict(int)
labels_all = []

for idx_list in metaidx:
    if cnt >= N:
        break
    labels = []
    for idx in idx_list:
        marco_embed[int(meta[idx])] += 1
        if idx != 0:
            labels.append(int(meta[idx]))
    labels_all.append(labels)
    cnt += 1

import os

file_path = os.path.join(marco_embed_dir, "marco.filter.base.new.txt")
label_type = np.int32
total_labels = 0

cnt = 0
with open(file_path, "w") as f:
    # data
    for labels in labels_all:
        cnt += 1
        is_written = False
        for label in labels:
            if is_written:
                f.write(',')
            f.write(str(label))
            is_written = True
            total_labels += 1
        if cnt < len(labels):
            f.write('\n')

print(f"{len(labels_all)} points with {total_labels} labels are written to {file_path}")

